create table if not exists public.gift_owner_keys (
  slug text primary key references public.gifts(slug) on delete cascade,
  token_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.gift_replies (
  id bigint generated by default as identity primary key,
  slug text not null references public.gifts(slug) on delete cascade,
  reaction text not null check (reaction in ('❤️','🥹','😍','🤍','🫶','💌')),
  message text not null default '' check (char_length(message) <= 500),
  created_at timestamptz not null default now()
);
create index if not exists gift_replies_slug_created_idx on public.gift_replies(slug, created_at desc);

create table if not exists public.site_events (
  id bigint generated by default as identity primary key,
  event text not null check (event in ('gift_start','payment_submitted','gift_view','reply_submitted')),
  slug text,
  created_at timestamptz not null default now()
);
create index if not exists site_events_event_created_idx on public.site_events(event, created_at desc);

alter table public.gift_owner_keys enable row level security;
alter table public.gift_replies enable row level security;
alter table public.site_events enable row level security;

